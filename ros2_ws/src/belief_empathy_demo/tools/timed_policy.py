# ─────────────────────────────────────────────────────────────── the model ──

def generated(model, roots):
    """The submodel generated by `roots`: the worlds some chain of the agents'
    relations reaches from them. Every formula keeps its truth at the roots."""
    seen, todo = set(roots), list(roots)
    while todo:
        w = todo.pop()
        for a in AGENTS:
            for v in model.image(a, w):
                if v not in seen:
                    seen.add(v)
                    todo.append(v)
    worlds = [w for w in model.worlds if w in seen]
    return Model(worlds, {a: {w: model.image(a, w) for w in worlds} for a in AGENTS},
                 {w: model.labels[w] for w in worlds}, model.designated & seen)


def contract(model, keep):
    """The bisimulation quotient of a model, with canonical names, and where
    each world of `keep` went.

    Worlds start in classes by their labels and are split by the classes their
    images reach, agent by agent, until no class splits. Classes are numbered
    by the order of their signatures in every round, so two isomorphic models
    get the same quotient, names included."""
    sig = {w: tuple(sorted(model.labels[w])) for w in model.worlds}
    order = sorted(set(sig.values()))
    cls = {w: order.index(sig[w]) for w in model.worlds}
    while True:
        sig = {w: (cls[w], tuple(tuple(sorted({cls[v] for v in model.image(a, w)})) for a in AGENTS))
               for w in model.worlds}
        order = {s: i for i, s in enumerate(sorted(set(sig.values())))}
        new = {w: order[sig[w]] for w in model.worlds}
        if len(order) == len(set(cls.values())):
            cls = new
            break
        cls = new
    rep = {}
    for w in model.worlds:
        rep.setdefault(cls[w], w)
    worlds = [f'c{c}' for c in sorted(rep)]
    labels = {f'c{c}': model.labels[w] for c, w in rep.items()}
    relations = {a: {f'c{c}': {f'c{cls[v]}' for v in model.image(a, w)} for c, w in rep.items()}
                 for a in AGENTS}
    designated = {f'c{cls[w]}' for w in model.designated}
    return Model(worlds, relations, labels, designated), {w: f'c{cls[w]}' for w in keep}


def canonical(model):
    """A contracted model as a value: its worlds, labels and relations by
    their canonical names."""
    return tuple((w, tuple(sorted(model.labels[w])), tuple(tuple(sorted(model.image(a, w))) for a in AGENTS))
                 for w in model.worlds)


def pattern_of(labels):
    """A designated world as estimate.py's fault pattern: each vehicle's drive
    faults and whether its tool has failed. A task without tools (the replica)
    has no tool faults."""
    def drive(g):
        return next(k for k in (1, 2, 3) if f'p{k}_{g}' in labels) - 1
    tools = any(a.startswith('tool_') for a in labels)

    def broken(g):
        return int(tools and f'tool_{g}' not in labels)
    return (drive('g1'), broken('g1'), drive('g2'), broken('g2'))


class Skeleton:
    """The epistemic states the search can reach, and the transitions between
    them: none of it depends on the site or the clock, so it is computed once
    for a task and kept. A state is a contracted model and the world each fault
    pattern still possible stands at; `info` keeps, per state, the patterns
    and the atoms true at all of their worlds, and `trans` maps a state and a
    grounded action to None, where the action is not applicable, or to the
    state each designated event that occurs leads to."""

    def __init__(self, task):
        self.task = task
        self.pre = {a: {e: convert(v['preconditions'][e]) for e in v['designated']}
                    for a, v in task['actions'].items()}
        self.index, self.models, self.info, self.trans = {}, {}, [], {}
        m0 = model_of(task['initial-state'])
        where0 = {pattern_of(m0.labels[w]): w for w in m0.designated}
        model, to = contract(generated(m0, where0.values()), where0.values())
        self.root = self.state(model, {p: to[w] for p, w in where0.items()})

    def state(self, model, where):
        key = (canonical(model), frozenset(where.items()))
        if key not in self.index:
            sid = len(self.info)
            self.index[key] = sid
            self.models[sid] = (model, where)
            worlds = list(where.values())
            common = set(model.labels[worlds[0]])
            for w in worlds[1:]:
                common &= model.labels[w]
            self.info.append((frozenset(where), frozenset(common)))
        return self.index[key]

    def branches(self, sid, name):
        if (sid, name) in self.trans:
            return self.trans[(sid, name)]
        model, where = self.models[sid]
        action = self.task['actions'][name]
        took = {}
        out = None
        for p, w in where.items():
            for i, e in enumerate(action['designated']):
                f = self.pre[name][e]
                if w in extensions(model, f)[f]:
                    took.setdefault(i, []).append(p)
                    break
            else:
                break
        else:
            out = {}
            for i, ps in took.items():
                e = action['designated'][i]
                mine = Model(model.worlds, model.relations, model.labels, {where[p] for p in ps})
                after, pairs = update(mine, action, AGENTS, [e])
                back = {(w, ev): n for n, (w, ev) in pairs.items()}
                moved = {p: back[(where[p], e)] for p in ps}
                quotient, to = contract(generated(after, moved.values()), moved.values())
                out[i] = self.state(quotient, {p: to[moved[p]] for p in ps})
        self.trans[(sid, name)] = out
        return out

    def save(self, path):
        with open(path, 'wb') as f:
            pickle.dump({'root': self.root, 'info': self.info, 'trans': self.trans,
                         'task_hash': self.task_hash}, f)

    @classmethod
    def load(cls, task, path):
        sk = cls.__new__(cls)
        sk.task = task
        with open(path, 'rb') as f:
            d = pickle.load(f)
        sk.root, sk.info, sk.trans, sk.task_hash = d['root'], d['info'], d['trans'], d['task_hash']
        sk.models, sk.index = None, None
        return sk


# ──────────────────────────────────────────────────────────── the search ──

class Node:
    """A state of the skeleton and the clock: where the aerial vehicle is, the
    time, when each vehicle sent reaches the site, the particle each vehicle
    met was found at, and the vehicles tried. `hold` is the time a drive just
    sent holds the policy until, where the drive answers on arrival."""
    __slots__ = ('sid', 'u', 't', 'arrive', 'met', 'tried', 'hold')

    def __init__(self, sid, u, t, arrive, met, tried, hold=None):
        self.sid, self.u, self.t = sid, u, t
        self.arrive, self.met, self.tried = arrive, met, tried
        self.hold = hold

    def at(self, sid):
        return Node(sid, self.u, self.t, self.arrive, self.met, self.tried, self.hold)

    def key(self):
        return (self.sid, round(self.u[0], 3), round(self.u[1], 3), round(self.t, 3),
                tuple(sorted((g, round(a, 3)) for g, a in self.arrive.items())),
                tuple(sorted(self.met.items())), tuple(sorted(self.tried)),
                None if self.hold is None else round(self.hold, 3))


class Planner:
    def __init__(self, skeleton, site, objective='mean', drive_blocks=False):
        self.sk, self.site = skeleton, tuple(site)
        self.objective = objective
        # ePlanSys's executor dispatches consecutive actions that name disjoint
        # agents as one group and waits for the whole group. Where a drive to
        # the site answers only on arrival (the replica's ground vehicles), the
        # aerial vehicle's next action runs beside the drive and the one after
        # it waits for the vehicle to arrive.
        self.drive_blocks = drive_blocks
        self.task = skeleton.task
        self.memo = {}
        self.expanded = 0

    def weight(self, sid):
        return len(self.sk.info[sid][0])

    def facts(self, sid):
        return self.sk.info[sid][1]

    def seek_actions(self, node, g):
        """The ways to hail g at a particle beyond those already passed: the
        grounded actions that take the aerial vehicle there (crossing first if
        g covers the other half) and the hail, with the particle. Which of
        them the task allows is the skeleton's to say."""
        f = self.facts(node.sid)
        cross = []
        if ('west_u' in f) != (f'west_{g}' in f):
            cross = ['cross-east_u' if 'west_u' in f else 'cross-west_u']
        passed = 2 if f'passed2_{g}' in f else 1 if f'passed1_{g}' in f else 0
        for k in range(passed + 1, 4):
            move = f'fly-p1_u_{g}' if k == 1 else f'back-p{k}_u_{g}'
            yield cross + [move, f'hail-p{k}_u_{g}'], k

    def quiet(self, node, name):
        """An action with one outcome here: its event index and the node after
        it, or None."""
        br = self.sk.branches(node.sid, name)
        if br is None or len(br) != 1:
            return None
        (i, sid), = br.items()
        return i, node.at(sid)

    def choices(self, node):
        for g in VEHICLES:
            if g not in node.met:
                for got in self.seek_actions(node, g):
                    yield 'seek', g, got
        for g in VEHICLES:
            if g in node.arrive and g not in node.tried:
                yield 'try', g, None

    def value(self, node):
        """(expected time, worst time, policy subtree, expected number of
        actions) from a node, the expectations over the patterns it holds
        possible."""
        key = node.key()
        if key in self.memo:
            return self.memo[key]
        self.expanded += 1
        best = (math.inf, math.inf, None, math.inf)
        for kind, g, extra in self.choices(node):
            got = self.seek(node, g, extra) if kind == 'seek' else self.attempt(node, g)
            if got is not None and self.rank(got) < self.rank(best):
                best = got
        self.memo[key] = best
        return best

    def rank(self, v):
        """The order choices are compared in: the expected time, then the
        worst; or with objective 'worst', the worst, then the expected. Last,
        fewer actions: where the aerial vehicle has time to spare, a hail
        that changes nothing in the model is not made, since a run late on
        the model would pay for it."""
        e, w = round(v[0], 6), round(v[1], 6)
        return ((e, w) if self.objective == 'mean' else (w, e)) + (round(v[3], 6),)

    @staticmethod
    def chain(prefix, last):
        tree = last
        for name, i in reversed(prefix):
            tree = {'action': name, 'branches': [{'event': i, 'subtree': tree}]}
        return tree

    def seek(self, node, g, extra):
        acts, k = extra
        prefix, cur = [], node
        hold = node.hold or 0.0
        for n_, name in enumerate(acts[:-1]):
            got = self.quiet(cur, name)
            if got is None:
                return None
            i, cur = got
            prefix.append((name, i))
            if not name.startswith('cross'):
                start = cur.t if n_ == 0 else max(cur.t, hold)
                u, t = L.intercept(cur.u, start, g, k)
                cur = Node(cur.sid, u, t, cur.arrive, cur.met, cur.tried)
        cur = Node(cur.sid, cur.u, max(cur.t, hold), cur.arrive, cur.met, cur.tried)
        hail = acts[-1]
        br = self.sk.branches(cur.sid, hail)
        if br is None:
            return None
        events = self.task['actions'][hail]['designated']
        total = sum(self.weight(sid) for sid in br.values())
        exp, worst, steps, kids = 0.0, 0.0, len(prefix) + 1.0, []
        for i, sid in sorted(br.items()):
            met = events[i].startswith('e-met-')
            t = cur.t + (E.HAIL_MET if met else L.HAIL_WINDOW)
            child = Node(sid, cur.u, t, cur.arrive, cur.met, cur.tried)
            send = None
            if met:
                # sent at once where the task lets it go; a vehicle that cannot
                # do the task (the replica's third particle) is not
                got = self.quiet(child, f'go-site_{g}')
                if got is None:
                    child = Node(child.sid, child.u, child.t, child.arrive, {**child.met, g: k}, child.tried)
                else:
                    gi, child = got
                    arrive = {**child.arrive, g: t + E.drive_to_site(L.particle(g, k, t), self.site, k - 1)}
                    child = Node(child.sid, child.u, child.t, arrive, {**child.met, g: k}, child.tried,
                                 arrive[g] if self.drive_blocks else None)
                    send = (f'go-site_{g}', gi)
            ce, cw, sub, cs = self.value(child)
            if not math.isfinite(ce):
                return None
            if send:
                sub = {'action': send[0], 'branches': [{'event': send[1], 'subtree': sub}]}
                cs += 1
            exp += ce * self.weight(sid) / total
            steps += cs * self.weight(sid) / total
            worst = max(worst, cw)
            kids.append({'event': i, 'subtree': sub})
        return exp, worst, self.chain(prefix, {'action': hail, 'branches': kids}), steps

    def attempt(self, node, g):
        prefix, cur = [], node
        hold = node.hold or 0.0
        if 'at-site_u' not in self.facts(cur.sid):
            got = self.quiet(cur, 'fly-site_u')
            if got is None:
                return None
            i, cur = got
            prefix.append(('fly-site_u', i))
            cur = Node(cur.sid, self.site, cur.t + E.fly(cur.u, self.site), cur.arrive, cur.met, cur.tried)
        name = f'perform_u_{g}'
        br = self.sk.branches(cur.sid, name)
        if br is None:
            return None
        events = self.task['actions'][name]['designated']
        t = max(cur.t, cur.arrive[g], hold) + L.DELTA
        total = sum(self.weight(sid) for sid in br.values())
        exp, worst, steps, kids = 0.0, 0.0, len(prefix) + 1.0, []
        for i, sid in sorted(br.items()):
            if events[i] != 'e-fail':
                ce, cw, sub, cs = t, t, None, 0.0
            else:
                ce, cw, sub, cs = self.value(Node(sid, cur.u, t, cur.arrive, cur.met, cur.tried | {g}))
                if not math.isfinite(ce):
                    return None
            exp += ce * self.weight(sid) / total
            steps += cs * self.weight(sid) / total
            worst = max(worst, cw)
            kids.append({'event': i, 'subtree': sub})
        return exp, worst, self.chain(prefix, {'action': name, 'branches': kids}), steps


def skeleton(task, site, u, t, cache=None):
    """The task's skeleton, from `cache` if it holds one for this task, built
    in full and saved there if not."""
    if cache and os.path.exists(cache):
        sk = Skeleton.load(task, cache)
        if sk.task_hash == task_hash(task):
            return sk
    sk = Skeleton(task)
    # every transition the search can take, whatever the site: the search's
    # choices do not depend on the clock, so one search anywhere visits them all
    Planner(sk, site).value(Node(sk.root, tuple(u), t, {}, {}, frozenset()))
    sk.task_hash = task_hash(task)
    if cache:
        sk.save(cache)
    return sk


def task_hash(task):
    return hashlib.sha256(json.dumps(task, sort_keys=True).encode()).hexdigest()


def plan(sk, site, u, t, objective='mean', drive_blocks=False):
    p = Planner(sk, site, objective, drive_blocks)
    start = time.time()
    exp, worst, policy, steps = p.value(Node(sk.root, tuple(u), t, {}, {}, frozenset()))
    return {'expected': exp, 'worst': worst, 'policy': policy, 'steps': steps, 'expanded': p.expanded,
            'seconds': time.time() - start}


def main():
    """As the planner command of ePlanSys's Aletheia plugin: the plugin passes
    --task and --plan (and --timeout, --consistent-beliefs, which do not
    apply); the launch adds the site and where the skeletons are kept."""
    ap = argparse.ArgumentParser()
    ap.add_argument('--task', required=True)
    ap.add_argument('--plan', required=True)
    ap.add_argument('--site', nargs=2, type=float, required=True)
    ap.add_argument('--start', nargs=3, type=float, help='the aerial vehicle at X Y at time T; by default '
                    'where and when its coverage route first sees the site')
    ap.add_argument('--skeletons', default=os.path.join(HERE, '..', 'policies', 'skeletons'),
                    help='a directory of skeletons, one per task, named by its hash')
    ap.add_argument('--objective', choices=('mean', 'worst'), default='mean')
    ap.add_argument('--drive-blocks', action='store_true',
                    help='a drive to the site answers on arrival and holds the executor\'s next group')
    a, _ = ap.parse_known_args()
    task = json.load(open(a.task))
    site = tuple(a.site)
    if a.start:
        u, t = (a.start[0], a.start[1]), a.start[2]
    else:
        import precheck
        u, t = precheck.found(site)
    os.makedirs(a.skeletons, exist_ok=True)
    cache = os.path.join(a.skeletons, task_hash(task)[:16] + '.skel')
    t0 = time.time()
    sk = skeleton(task, site, u, t, cache)
    built = time.time() - t0
    r = plan(sk, site, u, t, a.objective, a.drive_blocks)
    if r['policy'] is None:
        print(f'No solution: no policy reaches the goal from {a.task}')
        sys.exit(1)
    json.dump(r['policy'], open(a.plan, 'w'))
    print(f"Solution found: expected {r['expected']:.1f} s, worst {r['worst']:.1f} s at site {site}, "
          f"{r['expanded']} nodes in {r['seconds']:.2f} s; skeleton of {len(sk.info)} states "
          f"({'loaded' if built < 5 else 'built'} in {built:.1f} s)")


if __name__ == '__main__':
    main()
