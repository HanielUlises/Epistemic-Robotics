"""
A policy for the latent-tool-fault variant that minimises time, not steps.

    timed_policy.py TASK.json --site X Y [--start X Y T] [--out POLICY.json]

The search is an AND-OR search over the grounded EPDDL task. Its states are the
task's own pointed models, advanced by the product update of the repository's
tools/plan_trace.py and contracted to their bisimulation quotient after each
step. An action is applicable where the designated events of the action cover
the designated worlds, so every precondition of the task holds, the knowledge
precondition [g](task) of go-site among them. The branches of an action are
its designated events, each carrying away the designated worlds whose
precondition it satisfies. What the aerial vehicle knows when it chooses is
the set of designated worlds left, and nothing else: the fault budget and the
assumption that some tool works are in the initial model, and the search does
not restate them.

What the steps do not give is time. A node also carries a clock: where the
aerial vehicle is, the time, and when each vehicle that was sent reaches the
site. Durations are those of estimate.py's kinematic model, the ones
estimate.run_policy charges any policy, so a policy found here and one of
Aletheia's are timed alike. A branch's weight is the number of designated
worlds it carries, each fault pattern counting once, which is the seeds'
distribution. The search minimises the expected time to (done), the worst
case breaking ties, over choices made from the aerial vehicle's side:

  seek g    fly to g's next particle in route order (crossing first if g
            covers the other half) and hail; a vehicle met is sent at once,
            go-site naming it alone, which the executor runs alongside what
            the aerial vehicle does next
  try g     fly to the site if not there and perform with g, which has been
            sent and not tried

Sending a vehicle met at once costs the aerial vehicle nothing in this model,
so the search does not branch on it. The result is a policy in Aletheia's
format, which estimate.run_policy, trace_policy.py and ePlanSys's executor
read as they read Aletheia's.
"""

